#!/usr/bin/env python3
"""Subprocess native-library coexistence probe (PF18).

A duplicate LLVM image aborts the whole process while it is being loaded, so
the Torch/Triton/LLK import combination cannot be qualified in the launcher's
own process.  This worker imports the combination in the requested order and
writes one framed JSON result to stdout.  Upstream prints and native-loader
diagnostics stay on stderr.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

MARKER = "LLK-TRITON-COEXIST-V1"
PROTOCOL_VERSION = 1


def _emit(payload):
    body = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    stream = sys.__stdout__
    stream.write(f"{MARKER}\n{body}\n")
    stream.flush()


def _paths(args):
    if args.triton_python:
        sys.path.insert(0, args.triton_python)
    if args.llk_python:
        sys.path.insert(0, args.llk_python)


def _load(order):
    try:
        import torch  # noqa: F401
    except Exception:
        # Torch is optional for the import-order contract; a failure here is
        # not a Triton/LLK coexistence failure.
        pass
    loaded = {}
    if order == "triton-llk":
        import triton

        loaded["triton"] = str(getattr(triton, "__version__", ""))
        import llk.runtime._ffi as ffi

        loaded["api"] = int(ffi.library().llk_frontend_api_version())
    elif order == "llk-triton":
        import llk.runtime._ffi as ffi

        loaded["api"] = int(ffi.library().llk_frontend_api_version())
        import triton

        loaded["triton"] = str(getattr(triton, "__version__", ""))
    else:  # pragma: no cover - argv is generated by the launcher
        raise ValueError(f"unknown import order {order!r}")
    return loaded


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--order", required=True)
    parser.add_argument("--triton-python", default=None)
    parser.add_argument("--llk-python", default=None)
    args = parser.parse_args(argv)
    sys.stdout = sys.stderr
    try:
        _paths(args)
        loaded = _load(args.order)
        _emit(
            {
                "protocol_version": PROTOCOL_VERSION,
                "ok": True,
                "identity": loaded,
            }
        )
        return 0
    except BaseException as error:  # never let an exception escape unframed
        _emit(
            {
                "protocol_version": PROTOCOL_VERSION,
                "ok": False,
                "message": f"{type(error).__name__}: {error}",
            }
        )
        return 1


if __name__ == "__main__":
    sys.exit(main())
